#!/usr/bin/env julia

using LinearAlgebra
using Serialization
using SHA
using TOML

include(joinpath(@__DIR__, "common.jl"))
include(joinpath(@__DIR__, "ill_conditioned_lasso_cases.jl"))
using .RebuttalCommon
using .IllConditionedLassoCases

function atomic_toml(path::AbstractString, value::AbstractDict)
    mkpath(dirname(abspath(path)))
    temporary, stream = mktemp(dirname(abspath(path)))
    try
        TOML.print(stream, value; sorted = true)
        close(stream)
        mv(temporary, path; force = true)
    catch
        isopen(stream) && close(stream)
        isfile(temporary) && rm(temporary)
        rethrow()
    end
    return path
end

function atomic_serialize(path::AbstractString, value)
    mkpath(dirname(abspath(path)))
    temporary, stream = mktemp(dirname(abspath(path)))
    try
        serialize(stream, value)
        close(stream)
        mv(temporary, path; force = true)
    catch
        isopen(stream) && close(stream)
        isfile(temporary) && rm(temporary)
        rethrow()
    end
    return path
end

condition_tag(value::Real) = "kappa-1e$(round(Int, log10(Float64(value))))"

function main()
    VERSION == v"1.10.4" || error(
        "Instances must be generated by the shared Julia 1.10.4 binary; got $VERSION",
    )
    config_path = abspath(option(
        "config",
        joinpath(@__DIR__, "illcondition_lasso.toml"),
    ))
    output_dir = abspath(option("output-dir", joinpath(@__DIR__, "instances")))
    config = TOML.parsefile(config_path)
    get(config, "schema_version", 0) == 1 || error("unsupported config schema")
    config["generator_version"] == GENERATOR_VERSION || error(
        "generator version mismatch: config=$(config["generator_version"]) " *
        "code=$GENERATOR_VERSION",
    )
    config["julia_version"] == string(VERSION) || error("Julia version mismatch")
    dimension = Int(config["dimension"])
    dimension == 1000 || error("formal benchmark dimension must be 1000")
    condition_numbers = Float64.(config["condition_numbers"])
    all(value -> value > 1, condition_numbers) || error(
        "all condition numbers must exceed one",
    )
    issorted(condition_numbers) || error("condition numbers must be sorted")
    length(unique(condition_numbers)) == length(condition_numbers) || error(
        "condition numbers must be unique",
    )
    config["eigenvalue_spacing"] == "arithmetic" || error(
        "formal benchmark requires arithmetic eigenvalue spacing",
    )
    config["matrix_storage"] == "dense_float64" || error(
        "formal benchmark requires dense Float64 matrices",
    )

    mkpath(output_dir)
    source_sha256 = bytes2hex(sha256(read(config_path)))
    base = generate_family_base(
        dimension,
        Int(config["support_size"]),
        Int(config["seed"]),
    )
    entries = Any[]
    for condition_number in condition_numbers
        id = condition_tag(condition_number)
        println("INSTANCE_GENERATION_START id=$id kappa=$condition_number")
        started = time()
        instance = generate_instance(
            base,
            condition_number;
            lambda_ratio = Float64(config["lambda_ratio"]),
            noise_std = Float64(config["noise_std"]),
        )
        verification = verify_instance(instance)
        verification.condition_relative_error <= 1e-8 || error(
            "$id measured condition number mismatch: $verification",
        )
        verification.eigenvalue_spacing_error <= 1e-10 || error(
            "$id measured eigenvalues are not the requested arithmetic sequence",
        )
        verification.symmetry_error <= 1e-14 || error("$id is not symmetric")
        hashes = instance_hashes(instance)
        cache_name = "$id.jls"
        cache_path = joinpath(output_dir, cache_name)
        atomic_serialize(cache_path, instance)
        push!(entries, Dict{String,Any}(
            "id" => id,
            "condition_number" => condition_number,
            "dimension" => dimension,
            "cache" => cache_name,
            "cache_bytes" => filesize(cache_path),
            "matrix_sha256" => hashes.matrix,
            "b_sha256" => hashes.b,
            "xstar_sha256" => hashes.xstar,
            "eigenvalues_sha256" => hashes.eigenvalues,
            "dense_nonzeros" => verification.dense_nonzeros,
            "measured_condition_number" => verification.measured_condition_number,
            "condition_relative_error" => verification.condition_relative_error,
            "eigenvalue_spacing_error" => verification.eigenvalue_spacing_error,
            "symmetry_error" => verification.symmetry_error,
            "minimum_eigenvalue" => verification.minimum_eigenvalue,
            "maximum_eigenvalue" => verification.maximum_eigenvalue,
            "lambda" => instance.lambda,
            "generation_seconds" => time() - started,
        ))
        println(
            "INSTANCE_GENERATION_FINISH id=$id " *
            "measured_kappa=$(verification.measured_condition_number) " *
            "matrix_sha256=$(hashes.matrix) cache=$cache_path",
        )
    end

    manifest = Dict{String,Any}(
        "schema_version" => 1,
        "generator_version" => GENERATOR_VERSION,
        "source_config" => config_path,
        "source_config_sha256" => source_sha256,
        "julia_version" => string(VERSION),
        "dimension" => dimension,
        "matrix_storage" => "dense_float64",
        "matrix_structure" => "symmetric_positive_definite",
        "eigenvalue_spacing" => "arithmetic_descending",
        "shared_basis" => true,
        "seed" => Int(config["seed"]),
        "support_size" => Int(config["support_size"]),
        "lambda_ratio" => Float64(config["lambda_ratio"]),
        "noise_std" => Float64(config["noise_std"]),
        "instances" => entries,
    )
    manifest_path = joinpath(output_dir, "generated_instances.toml")
    atomic_toml(manifest_path, manifest)
    println("ILL_CONDITIONED_INSTANCES_READY count=$(length(entries)) manifest=$manifest_path")
    return manifest_path
end

main()
